#!/usr/bin/env node
/**
 * Release helper — one source of truth for the version.
 *   npm run release -- 0.5.0 "Short description"   bump package.json + version.ts, move CHANGELOG "Unreleased" to the version, commit, tag v0.5.0
 *   npm run version:check                           verify package.json, version.ts and the latest CHANGELOG entry agree
 * Push afterwards with: git push && git push --tags
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const pkgPath = 'package.json', verPath = 'packages/core/src/version.ts', logPath = 'CHANGELOG.md';
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
const inTs = readFileSync(verPath, 'utf8').match(/VERSION = '([^']+)'/)?.[1];
const log = readFileSync(logPath, 'utf8');
const inLog = log.match(/^## \[(\d+\.\d+\.\d+)\]/m)?.[1];

if (process.argv.includes('--check')) {
  const ok = pkg.version === inTs && pkg.version === inLog;
  console.log(`package.json ${pkg.version} · version.ts ${inTs} · CHANGELOG ${inLog} → ${ok ? 'consistent' : 'MISMATCH'}`);
  process.exit(ok ? 0 : 1);
}

const next = process.argv[2];
if (!/^\d+\.\d+\.\d+$/.test(next ?? '')) { console.error('gebruik: npm run release -- <x.y.z> ["omschrijving"]'); process.exit(1); }
const dirty = execFileSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).trim();
if (dirty) { console.error('werkmap is niet schoon; commit of stash eerst:\n' + dirty); process.exit(1); }
if (!/^## \[Unreleased\]\n(?:(?!## \[).*\n)*?\S/m.test(log)) { console.error('CHANGELOG.md heeft geen regels onder "## [Unreleased]"; beschrijf eerst wat er in deze release zit.'); process.exit(1); }

pkg.version = next;
writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
writeFileSync(verPath, `// Generated by scripts/release.mjs — do not edit by hand.\nexport const VERSION = '${next}';\n`);
const today = new Date().toISOString().slice(0, 10);
writeFileSync(logPath, log.replace('## [Unreleased]\n', `## [Unreleased]\n\n## [${next}] — ${today}\n`));
const msg = process.argv[3] ? `Release ${next}: ${process.argv[3]}` : `Release ${next}`;
execFileSync('git', ['add', pkgPath, verPath, logPath]);
execFileSync('git', ['commit', '-q', '-m', msg]);
execFileSync('git', ['tag', '-a', `v${next}`, '-m', msg]);
console.log(`✔ ${msg}\n  tag v${next} gezet — push met: git push && git push --tags`);
